//! Shared types for RadioDoge.
//!
//! All types derive Serialize/Deserialize so they can be sent
//! over Tauri IPC to the Svelte frontend or printed from the CLI.

use serde::{Deserialize, Serialize};

/// LoRa radio statistics — updated every 2 seconds when connected.
#[derive(Debug, Clone, Serialize, Deserialize)]
#[serde(rename_all = "camelCase")]
pub struct RadioStats {
    /// Frequency in MHz (e.g. 915.0)
    pub frequency_mhz: f32,
    /// TX power in dBm (5–20)
    pub power_dbm: i8,
    /// LoRa spreading factor (7–12)
    pub spreading_factor: u8,
    /// Bandwidth in kHz (125, 250, or 500)
    pub bandwidth_khz: f32,
    /// Coding rate string (e.g. "4/5")
    pub coding_rate: String,
    /// Last received RSSI in dBm (typically -50 to -120)
    pub rssi: i16,
    /// Last received SNR in dB
    pub snr: f32,
    /// Total packets sent this session
    pub packets_sent: u32,
    /// Total packets received this session
    pub packets_received: u32,
}

impl Default for RadioStats {
    fn default() -> Self {
        RadioStats {
            frequency_mhz: 915.0,
            power_dbm: 5,
            spreading_factor: 7,
            bandwidth_khz: 125.0,
            coding_rate: "4/5".to_string(),
            rssi: -120,
            snr: 0.0,
            packets_sent: 0,
            packets_received: 0,
        }
    }
}

/// RadioDoge mesh network address: Region.Community.Node
/// Example: 10.0.2 means Region=10, Community=0, Node=2
#[derive(Debug, Clone, Serialize, Deserialize, PartialEq)]
#[serde(rename_all = "camelCase")]
pub struct NodeAddress {
    pub region: u8,
    pub community: u8,
    pub node: u8,
}

impl NodeAddress {
    pub fn new(region: u8, community: u8, node: u8) -> Self {
        NodeAddress { region, community, node }
    }

    /// Broadcast address: 255.255.255
    pub fn broadcast() -> Self {
        NodeAddress { region: 0xFF, community: 0xFF, node: 0xFF }
    }

    /// Default local address: 10.0.1
    pub fn default_local() -> Self {
        NodeAddress { region: 10, community: 0, node: 1 }
    }

    pub fn to_display_string(&self) -> String {
        format!("{}.{}.{}", self.region, self.community, self.node)
    }
}

impl Default for NodeAddress {
    fn default() -> Self {
        NodeAddress::default_local()
    }
}

/// Dogecoin wallet information generated by the app.
/// The private key is in WIF format (starts with "Q" for mainnet compressed).
/// ⚠️  NEVER log or transmit the private key!
#[derive(Debug, Clone, Serialize, Deserialize)]
#[serde(rename_all = "camelCase")]
pub struct WalletInfo {
    /// Dogecoin address, starts with "D" on mainnet
    pub address: String,
    /// Compressed public key as hex string (66 chars)
    pub public_key_hex: String,
    /// Private key in WIF format (starts with "Q" for compressed mainnet)
    pub private_key_wif: String,
}

