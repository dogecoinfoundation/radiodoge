/// A transaction request from the Send tab.
#[derive(Debug, Clone, Serialize, Deserialize)]
#[serde(rename_all = "camelCase")]
pub struct TransactionRequest {
    /// Recipient Dogecoin address
    pub to_address: String,
    /// Amount in DOGE
    pub amount_doge: f64,
    /// Optional memo (sent in LoRa packet payload)
    pub memo: Option<String>,
    /// Sender's WIF private key (from generated wallet)
    pub from_private_key_wif: Option<String>,
}

/// An incoming LoRa packet captured by the receive loop.
#[derive(Debug, Clone, Serialize, Deserialize)]
#[serde(rename_all = "camelCase")]
pub struct IncomingPacket {
    /// Unix timestamp (seconds)
    pub timestamp: u64,
    /// Source node address
    pub source: NodeAddress,
    /// Destination node address
    pub destination: NodeAddress,
    /// Command type byte
    pub command: u8,
    /// Raw payload as hex string
    pub payload_hex: String,
    /// Human-readable decoded content (if parseable)
    pub decoded: Option<String>,
    /// RSSI of this packet in dBm
    pub rssi: i16,
}

/// v0.3.6 — Board-is-source-of-truth: live state reported by the Heltec device
